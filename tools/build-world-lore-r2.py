import json

def entry(uid, name, gates, body, order):
    keys = gates
    cond = ' || '.join(f"chat.match('{g}')" for g in gates)
    content = "<% if (" + cond + ") { %>\n<" + name + ">\n" + body.strip() + "\n</" + name + ">\n<% } %>"
    return {'uid': uid, 'name': name, 'content': content, 'enabled': True,
            'constant': False, 'key': keys, 'keysecondary': [],
            'selectiveLogic': 0, 'order': order, 'position': 0}

def append_book(path, new_entries):
    book = json.load(open(path, encoding='utf-8'))
    uids = {e['uid'] for e in book['entries']}
    added = 0
    for e in new_entries:
        if e['uid'] in uids:
            book['entries'] = [x for x in book['entries'] if x['uid'] != e['uid']]
        else:
            added += 1
        book['entries'].append(e)
    book['entries'].sort(key=lambda x: x['uid'])
    json.dump(book, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f"{path}: 新增{added} 覆盖{len(new_entries)-added} → {len(book['entries'])} 条")

