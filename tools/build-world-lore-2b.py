import json

def entry(uid, name, gates, body, order, keep_keys=None):
    keys = keep_keys if keep_keys is not None else gates
    cond = ' || '.join(f"chat.match('{g}')" for g in gates)
    content = "<% if (" + cond + ") { %>\n<" + name + ">\n" + body.strip() + "\n</" + name + ">\n<% } %>"
    return {'uid': uid, 'name': name, 'content': content, 'enabled': True,
            'constant': False, 'key': keys, 'keysecondary': [],
            'selectiveLogic': 0, 'order': order, 'position': 0}

