race = json.load(open('worldbooks/race.json', encoding='utf-8'))
E = {e['name']: e for e in race['entries']}
existing_keys = {e['name']: e.get('key') for e in race['entries']}
for uid, name, gates, body, order in RACE:
    keep = existing_keys.get(name)
    new = entry(uid, name, gates, body, order, keep_keys=keep)
    if name in E:
        E[name]['content'] = new['content']
        E[name]['key'] = new['key']
        E[name]['order'] = order
    else:
        race['entries'].append(new)
# 删除旧合条
race['entries'] = [e for e in race['entries'] if e['name'] != '非人诸族']
race['description'] = '诸族条目：人类/近人诸族/异形诸族/高位铭灵，含灭铭之战站位史（chat.match 门控）。'
json.dump(race, open('worldbooks/race.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('race:', len(race['entries']), '条（合条已拆）')

