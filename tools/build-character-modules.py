p = 'worldbooks/character.json'
book = json.load(open(p, encoding='utf-8'))
names = {e['name'] for e in book['entries']}
added = []
for uid, name, gates, body, order, const in MODULES:
    if name in names:
        continue
    book['entries'].append(entry(uid, name, gates, body, order, const))
    added.append(name)
