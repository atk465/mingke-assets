# 草棘狼/律兽/无名之物/蚀币鼠 + 剩余条目
def apply(fname, fixes):
    p = 'worldbooks/' + fname
    book = json.load(open(p, encoding='utf-8'))
    for e in book['entries']:
        if e['name'] in fixes:
            for old, new in fixes[e['name']]:
                if new is None or old not in e['content']:
                    continue  # 已应用或占位，跳过（幂等）
                e['content'] = e['content'].replace(old, new)
    json.dump(book, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

